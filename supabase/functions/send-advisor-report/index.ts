import { serve } from "https://deno.land/std@0.190.0/http/server.ts";
import {
  handleCors,
  createSuccessResponse,
  createErrorResponse,
} from "../_shared/response.ts";

const RESEND_API_KEY = Deno.env.get("RESEND_API_KEY");

interface AdvisorReportRequest {
  advisorEmail: string;
  advisorName?: string;
  personalMessage?: string;
  reportType: string;
  reportName: string;
  summaryData: {
    score?: number;
    highlights?: string[];
    recommendations?: string[];
    completedAt?: string;
  };
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function generateReportHtml(data: AdvisorReportRequest): string {
  const { reportName, summaryData, personalMessage, advisorName } = data;
  const greeting = advisorName ? `Dear ${escapeHtml(advisorName)}` : "Dear Advisor";

  let highlightsHtml = "";
  if (summaryData.highlights && summaryData.highlights.length > 0) {
    highlightsHtml = `
      <h3 style="color:#1a1a1a;margin-top:24px;margin-bottom:12px;">Key Findings</h3>
      <ul style="color:#4a4a4a;padding-left:20px;">
        ${summaryData.highlights.map((h) => `<li style="margin-bottom:8px;">${escapeHtml(h)}</li>`).join("")}
      </ul>`;
  }

  let recommendationsHtml = "";
  if (summaryData.recommendations && summaryData.recommendations.length > 0) {
    recommendationsHtml = `
      <h3 style="color:#1a1a1a;margin-top:24px;margin-bottom:12px;">Recommendations</h3>
      <ul style="color:#4a4a4a;padding-left:20px;">
        ${summaryData.recommendations.map((r) => `<li style="margin-bottom:8px;">${escapeHtml(r)}</li>`).join("")}
      </ul>`;
  }

  let personalMessageHtml = "";
  if (personalMessage) {
    personalMessageHtml = `
      <div style="background-color:#f8f9fa;border-left:4px solid #6366f1;padding:16px;margin-top:24px;border-radius:4px;">
        <p style="margin:0;color:#4a4a4a;font-style:italic;">"${escapeHtml(personalMessage)}"</p>
        <p style="margin:8px 0 0;color:#6b7280;font-size:14px;">— Client's personal note</p>
      </div>`;
  }

  return `<!DOCTYPE html><html><head><meta charset="utf-8"><title>SCRF Hub - ${escapeHtml(reportName)} Report</title></head>
<body style="font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;line-height:1.6;color:#1a1a1a;max-width:600px;margin:0 auto;padding:20px;">
  <div style="text-align:center;padding:24px 0;border-bottom:2px solid #e5e7eb;">
    <h1 style="color:#6366f1;margin:0;font-size:28px;">SCRF Hub</h1>
    <p style="color:#6b7280;margin:8px 0 0;font-size:14px;">Strategic Compliance & Risk Framework</p>
  </div>
  <div style="padding:32px 0;">
    <p style="color:#4a4a4a;">${greeting},</p>
    <p style="color:#4a4a4a;">Your client has completed a <strong>${escapeHtml(reportName)}</strong> assessment using the SCRF Hub and would value your professional feedback on the results.</p>
    ${summaryData.score !== undefined ? `<div style="background:linear-gradient(135deg,#6366f1 0%,#8b5cf6 100%);color:white;padding:24px;border-radius:12px;text-align:center;margin:24px 0;"><p style="margin:0;font-size:14px;opacity:0.9;">Assessment Score</p><p style="margin:8px 0 0;font-size:48px;font-weight:bold;">${summaryData.score}%</p><p style="margin:8px 0 0;font-size:14px;opacity:0.9;">Completed: ${summaryData.completedAt || new Date().toLocaleDateString()}</p></div>` : ""}
    ${highlightsHtml}${recommendationsHtml}${personalMessageHtml}
    <div style="background-color:#f3f4f6;padding:20px;border-radius:8px;margin-top:32px;text-align:center;">
      <p style="margin:0 0 12px;color:#4a4a4a;"><strong>Next Steps:</strong> Your client is looking for your professional guidance on these findings.</p>
    </div>
    <div style="margin-top:32px;padding-top:24px;border-top:1px solid #e5e7eb;">
      <p style="color:#6b7280;font-size:14px;"><strong>About the SCRF Hub:</strong> The Strategic Compliance & Risk Framework Hub is a digital toolkit helping SMEs identify and manage operational, financial, compliance, and strategic risks. Learn more at <a href="https://tsadinaledi.lovable.app" style="color:#6366f1;">tsadinaledi.lovable.app</a></p>
    </div>
  </div>
  <div style="text-align:center;padding:24px 0;border-top:1px solid #e5e7eb;color:#6b7280;font-size:12px;">
    <p style="margin:0;">This report was generated by SCRF Hub</p>
    <p style="margin:4px 0 0;">© ${new Date().getFullYear()} Tsadi Naledi. All rights reserved.</p>
  </div>
</body></html>`;
}

const handler = async (req: Request): Promise<Response> => {
  const cors = handleCors(req);
  if (cors) return cors;

  try {
    const requestData: AdvisorReportRequest = await req.json();

    if (!requestData.advisorEmail || !requestData.reportType || !requestData.reportName) {
      return createErrorResponse("Missing required fields", 400, "VALIDATION_ERROR");
    }

    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(requestData.advisorEmail)) {
      return createErrorResponse("Invalid email address", 400, "VALIDATION_ERROR");
    }

    if (requestData.advisorEmail.length > 255) {
      return createErrorResponse("Email address too long", 400, "VALIDATION_ERROR");
    }

    const htmlContent = generateReportHtml(requestData);

    const resendResponse = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${RESEND_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        from: "SCRF Hub <onboarding@resend.dev>",
        to: [requestData.advisorEmail],
        subject: `SCRF Hub: ${requestData.reportName} Assessment Report`,
        html: htmlContent,
      }),
    });

    if (!resendResponse.ok) {
      const errorData = await resendResponse.text();
      console.error("Resend API error:", errorData);
      return createErrorResponse("Failed to send email", 500, "EMAIL_SEND_FAILED", true);
    }

    const emailResult = await resendResponse.json();
    return createSuccessResponse({ sent: true, messageId: emailResult.id });
  } catch (error: unknown) {
    const message = error instanceof Error ? error.message : "Unknown error";
    console.error("send-advisor-report error:", message);
    return createErrorResponse(message, 500, "INTERNAL_ERROR", true);
  }
};

serve(handler);
