import jsPDF from 'jspdf';

export interface PDFReportData {
  reportTitle: string;
  reportType: string;
  score?: number;
  grade?: string;
  completedAt?: string;
  sections: PDFSection[];
  userName?: string;
  companyName?: string;
}

export interface PDFSection {
  title: string;
  items: { label: string; value: string; highlight?: 'success' | 'warning' | 'danger' }[];
}

const COLORS = {
  primary: [45, 134, 117] as [number, number, number],
  primaryLight: [220, 245, 240] as [number, number, number],
  dark: [35, 45, 55] as [number, number, number],
  muted: [120, 130, 140] as [number, number, number],
  white: [255, 255, 255] as [number, number, number],
  border: [220, 225, 230] as [number, number, number],
  success: [34, 139, 34] as [number, number, number],
  warning: [200, 140, 20] as [number, number, number],
  danger: [200, 50, 50] as [number, number, number],
  accent: [230, 100, 60] as [number, number, number],
};

export function generatePDFReport(data: PDFReportData): jsPDF {
  const doc = new jsPDF('p', 'mm', 'a4');
  const pageWidth = 210;
  const margin = 20;
  const contentWidth = pageWidth - margin * 2;
  let y = 0;

  // --- Header bar ---
  doc.setFillColor(...COLORS.primary);
  doc.rect(0, 0, pageWidth, 38, 'F');
  
  doc.setTextColor(...COLORS.white);
  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text('SCRF Hub', margin, 18);
  
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text('Strategic Compliance & Risk Framework', margin, 26);
  
  // Date
  doc.setFontSize(8);
  doc.text(
    `Generated: ${data.completedAt || new Date().toLocaleDateString()}`,
    pageWidth - margin,
    26,
    { align: 'right' }
  );
  
  y = 48;

  // --- Report title ---
  doc.setTextColor(...COLORS.dark);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text(data.reportTitle, margin, y);
  y += 8;

  if (data.userName || data.companyName) {
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(...COLORS.muted);
    const meta = [data.companyName, data.userName].filter(Boolean).join(' • ');
    doc.text(meta, margin, y);
    y += 6;
  }

  // --- Score card ---
  if (data.score !== undefined || data.grade) {
    y += 4;
    doc.setFillColor(...COLORS.primaryLight);
    doc.roundedRect(margin, y, contentWidth, 28, 3, 3, 'F');
    
    doc.setFillColor(...COLORS.primary);
    doc.roundedRect(margin + 4, y + 4, 40, 20, 2, 2, 'F');
    doc.setTextColor(...COLORS.white);
    doc.setFontSize(20);
    doc.setFont('helvetica', 'bold');
    const scoreText = data.grade || `${data.score}%`;
    doc.text(scoreText, margin + 24, y + 17, { align: 'center' });

    doc.setTextColor(...COLORS.dark);
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.text('Assessment Score', margin + 52, y + 12);
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(...COLORS.muted);
    doc.text(`Report: ${data.reportType}`, margin + 52, y + 20);

    y += 36;
  }

  // --- Sections ---
  for (const section of data.sections) {
    // Check if we need a new page
    if (y > 260) {
      doc.addPage();
      y = 20;
    }

    y += 4;
    // Section header
    doc.setFillColor(...COLORS.primary);
    doc.rect(margin, y, 3, 7, 'F');
    doc.setTextColor(...COLORS.dark);
    doc.setFontSize(13);
    doc.setFont('helvetica', 'bold');
    doc.text(section.title, margin + 7, y + 6);
    y += 14;

    for (const item of section.items) {
      if (y > 270) {
        doc.addPage();
        y = 20;
      }

      const highlightColor = item.highlight === 'success' ? COLORS.success
        : item.highlight === 'warning' ? COLORS.warning
        : item.highlight === 'danger' ? COLORS.danger
        : COLORS.dark;

      doc.setFontSize(9);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(...COLORS.muted);
      doc.text(item.label, margin + 4, y);

      doc.setFont('helvetica', 'normal');
      doc.setTextColor(...highlightColor);
      
      // Word-wrap long values
      const lines = doc.splitTextToSize(item.value, contentWidth - 8);
      doc.text(lines, margin + 4, y + 5);
      y += 5 + lines.length * 4 + 3;
    }

    // Divider
    doc.setDrawColor(...COLORS.border);
    doc.line(margin, y, pageWidth - margin, y);
    y += 4;
  }

  // --- Footer ---
  const addFooter = (pageDoc: jsPDF, pageNum: number) => {
    pageDoc.setFontSize(7);
    pageDoc.setTextColor(...COLORS.muted);
    pageDoc.text(
      'This report was generated by SCRF Hub — Strategic Compliance & Risk Framework. For professional advice, consult a qualified advisor.',
      margin,
      287
    );
    pageDoc.text(`Page ${pageNum}`, pageWidth - margin, 287, { align: 'right' });
    pageDoc.text('© Tsadi Naledi. All rights reserved.', margin, 291);
  };

  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addFooter(doc, i);
  }

  return doc;
}

export function downloadPDF(data: PDFReportData, filename?: string) {
  const doc = generatePDFReport(data);
  const safeName = filename || `SCRF_${data.reportType.replace(/\s+/g, '_')}_${new Date().toISOString().slice(0, 10)}.pdf`;
  doc.save(safeName);
}
